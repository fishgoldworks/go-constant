'use strict';

const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const { headingsIn } = require('./documentation-schema');

// The reference owns the complete summary; the overview only changes its links.
function renderDocuments(templates, metadata, api, render) {
  const reference = render(templates.API, metadata, api);
  const { headings, lines } = headingsIn(reference);
  const start = headings.find((h) => h.level === 2 && h.title === 'API summary');

  assert.ok(start, 'Missing API summary');
  const end = headings.find((h) => h.index > start.index && h.level <= 2);
  const summary = lines
    .slice(start.index + 1, end ? end.index : lines.length)
    .join('\n')
    .trim();

  assert.equal(templates.README.split('{{API_SUMMARY}}').length, 2, 'Expected one API summary placeholder');
  const localAnchors = new Set(
    headings.filter((h) => h.index > start.index && (!end || h.index < end.index)).map((h) => h.anchor)
  );
  const overview = templates.README.replace('{{API_SUMMARY}}', () =>
    summary.replace(/\]\(#([^)]+)\)/g, (link, anchor) =>
      localAnchors.has(anchor) ? link : '](docs/API.md#' + anchor + ')'
    )
  );
  const documents = {
    'README.md': render(overview, metadata, api, templates.API),
    'docs/API.md': reference
  };

  for (const [name, text] of Object.entries(documents)) {
    const template = name === 'README.md' ? 'README' : 'API';

    documents[name] = text.replace(
      /^(# .+\n)/,
      '$1\n<!-- Generated by npm run docs; edit scripts/' + template + '.template.md. -->\n'
    );
  }

  validateLinks(documents);

  return documents;
}

function repositoryDocuments(documents, root) {
  const sources = { ...documents };
  const addFile = (file) => {
    if (!Object.hasOwn(sources, file) && fs.existsSync(path.join(root, file))) {
      sources[file] = fs.readFileSync(path.join(root, file), 'utf8');
    }
  };

  const addDirectory = (directory) => {
    const absolute = path.join(root, directory);

    if (!fs.existsSync(absolute)) {
      return;
    }

    for (const entry of fs.readdirSync(absolute, { withFileTypes: true })) {
      const file = path.posix.join(directory, entry.name);

      if (entry.isDirectory()) {
        if (entry.name !== 'temp' && entry.name !== '.tmp' && file !== 'docs/performance-history') {
          addDirectory(file);
        }
      } else if (entry.isFile() && /\.md$/i.test(entry.name)) {
        addFile(file);
      }
    }
  };

  for (const file of ['AGENTS.md', 'CONTRIBUTING.md', 'CHANGELOG.md', 'LICENSE.md', 'benchmarks/README.md']) {
    addFile(file);
  }

  addDirectory('docs');

  return sources;
}

function validateLinks(documents, root) {
  const sources = root ? repositoryDocuments(documents, root) : documents;

  for (const [name, text] of Object.entries(sources)) {
    for (const [, link] of text.matchAll(/\]\(([^)\s]+)\)/g)) {
      if (/^(?:[a-z]+:|\/\/)/i.test(link)) continue;
      const [file, fragment] = link.split('#');
      const target = file ? path.posix.normalize(path.posix.join(path.posix.dirname(name), file)) : name;
      const source = Object.hasOwn(sources, target)
        ? sources[target]
        : root && fs.existsSync(path.join(root, target))
          ? fs.readFileSync(path.join(root, target), 'utf8')
          : undefined;

      if (root || !file || Object.hasOwn(sources, target))
        assert.equal(typeof source, 'string', name + ': missing document ' + link);
      if (fragment && source !== undefined)
        assert.ok(headingsIn(source).anchors.has(fragment), name + ': missing fragment ' + link);
    }
  }
}

module.exports = { renderDocuments, validateLinks };
